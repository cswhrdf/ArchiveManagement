"""界面度量刻度: 间距、圆角与字号的唯一来源.

为什么需要这个模块: 界面评审里"间距/字号/圆角"这一类问题的共同形状是**同一个角色在不同
页面用了不同的数字** -- 同样"面板内边距", 主页写 18, 设置窗口写 16; 同样"卡片圆角", 一处 8
一处 11 一处 12。数字散落在各页面里, 既查不出"谁跟谁本该一样", 也挡不住下一个新写的 7 或 13。

因此把刻度收成三张短表:

- **间距**: 2px 网格, 12 以内步长 2(控件内部要靠得紧), 12 以上步长 4(区块之间要拉开) --
  一共 10 档: ``SPACE_0`` / ``SPACE_2`` / ... / ``SPACE_24``;
- **圆角**: 5 档 ``RADIUS_NONE``(直角容器) / ``RADIUS_PILL``(胶囊) / ``RADIUS_SM``(小内嵌块) /
  ``RADIUS_MD``(按钮、输入框) / ``RADIUS_LG``(卡片、面板);
- **字号**: 见 :mod:`archive_management.ui.typography` 的 ``FONT_*`` 阶梯(它同时是 rem 换算的落点)。

实测(2026-09-27, 探针读 ast 统计界面模块): ``padx`` 341 处 / ``pady`` 436 处 /
``corner_radius`` 73 处 / ``CTkFont(size=...)`` 173 处, 其中**不在刻度上的**分别是 93 / 7 / 8 处
-- 这 108 处就是 I-5 收敛掉的清单。收敛时按**角色**取值, 不取"最近的那个数":

- 面板与窗口内容距边统一 16(设置/管理/定时窗口的面板本来就是 16, 主页的 18 是少数派);
- 对话框正文距顶与按钮行距底统一 20(原来 22/20/14 与 18/20/16 各写一套);
- 区块之间的竖向间距统一 16, 列表行的最小间隔统一 2, 定时任务行内衬统一 8。

收敛之后守卫再扫一遍(``tests/unit/test_ui_metrics.py``, 19 个界面模块): 775 处 ``padx``/``pady``、
65 处 ``corner_radius``、169 处字号, **一处越界都没有**。几个数与上面的 777 / 73 / 173 对不上是
因为: 8 处圆角与 4 处字号换成了下面这些常量名, 另有 2 个数字(那个 24 + 22 的对齐缩进)进了
具名常量。

一个**具名常量**是允许的出口: 像"勾选行下面那行提示与复选框文字对齐"这种**量出来**的缩进
(24 正文边 + 22 方框宽与间距)没法落在刻度上, 就写成一个带注释的模块级常量 -- 至少它能被
grep 到、有理由可查。守卫只拦"伸手就写的数字", 详见 ``tests/unit/test_ui_metrics.py``。
"""

from __future__ import annotations

# -- 间距 -------------------------------------------------------------------

#: 刻度里的每一档(名字带上值, 便于在调用点直接读出像素数).
SPACE_0 = 0
SPACE_2 = 2
SPACE_4 = 4
SPACE_6 = 6
SPACE_8 = 8
SPACE_10 = 10
SPACE_12 = 12
SPACE_16 = 16
SPACE_20 = 20
SPACE_24 = 24

#: 允许出现在 ``padx`` / ``pady`` 里的全部值(守卫按这张表判).
SPACE_SCALE = (
    SPACE_0,
    SPACE_2,
    SPACE_4,
    SPACE_6,
    SPACE_8,
    SPACE_10,
    SPACE_12,
    SPACE_16,
    SPACE_20,
    SPACE_24,
)

# -- 圆角 -------------------------------------------------------------------

#: 直角: 整页容器(页面/分区/正文区).
RADIUS_NONE = 0
#: 胶囊: 只有"高度 = 2 x 半径"的进度条用, 别拿去画面板.
RADIUS_PILL = 4
#: 小内嵌块: 对话框里的提示块、批量导出的行卡片、海报封面框、状态点.
RADIUS_SM = 6
#: 常规控件: 按钮、输入框、下拉框、页签.
RADIUS_MD = 8
#: 卡片与面板: 备份卡片、设置窗口的分组面板、主窗口的右侧面板.
RADIUS_LG = 10

#: 允许出现在 ``corner_radius`` 里的全部值(守卫按这张表判).
RADIUS_SCALE = (
    RADIUS_NONE,
    RADIUS_PILL,
    RADIUS_SM,
    RADIUS_MD,
    RADIUS_LG,
)

#: 刻度到名字的对照(守卫报错时用来说清"该写哪一个").
RADIUS_NAMES = {
    RADIUS_NONE: "RADIUS_NONE",
    RADIUS_PILL: "RADIUS_PILL",
    RADIUS_SM: "RADIUS_SM",
    RADIUS_MD: "RADIUS_MD",
    RADIUS_LG: "RADIUS_LG",
}
